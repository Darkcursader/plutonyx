// Portions of this code were generated with the assistance of an SI tool (Claude) and reviewed by Team PlutonyX.
// Writes "golden runs": for a few seeds and strategies, the exact state after every sol and the final
// ending, as computed by the reference simulator. The Unity edition's EditMode tests replay the same
// inputs through the C# port and must get the same numbers (to 3 decimals). The Web edition can do the same.
// Usage: node tools/sim/golden.js OUT_FILE
'use strict';
const fs = require('fs');
const { createMission, makeRng } = require('./sim.js');
const { world, bots } = require('./run.js');
const out = process.argv[2];
const cases = [];
for (const [timeline, difficulty, botName, seed] of [
  ['may-2024', 'commander', 'balanced', 42], ['may-2024', 'commander', 'bold', 7], ['may-2024', 'cadet', 'gardener', 1234],
  ['may-2024', 'commander', 'expert', 2024], ['may-2024', 'commander', 'cautious', 99], ['may-2024', 'commander', 'random', 5],
  ['may-2024', 'cadet', 'casual', 31337], ['sep-2017', 'commander', 'balanced', 11], ['recent', 'commander', 'casual', 77]]) {
  const w = world(timeline), bot = bots[botName];
  const m = createMission(w, { seed, difficulty }), r = makeRng(seed * 7919 + 13);
  const sols = [];
  while (!m.state.over) {
    const info = m.beginSol(), answers = [];
    for (const e of info.events) { const c = bot.answer(m, e, r); m.choose(e.id, c); answers.push([e.id, c]); }
    const plan = bot.plan(m, info, r), crisis = m.startSol(plan), crisisAnswers = [];
    for (const e of crisis) { const c = bot.crisis(m, e, r); m.choose(e.id, c); crisisAnswers.push([e.id, c]); }
    const rep = m.finishSol();
    sols.push({ events: info.events.map(e => e.id), answers, plan, crisis: crisis.map(e => e.id), crisisAnswers,
                env: { kind: rep.env.kind, dose: Math.round(rep.env.dose * 1000) / 1000 }, after: rep.state });
  }
  const e = m.ending();
  cases.push({ timeline, difficulty, bot: botName, seed, baselineSol: Math.round(w.env.baselineSol * 1000) / 1000,
               doseBudget: Math.round(m.doseBudget * 1000) / 1000, sols, ending: e.ending.id, summary: e.summary });
}
fs.writeFileSync(out, JSON.stringify({ schema: 'plutonyx.golden/1', note: 'Generated by tools/sim/golden.js. Do not edit by hand.', cases }, null, 1));
console.log('wrote', out, cases.length, 'cases:', cases.map(c => c.bot + '->' + c.ending).join(', '));
